"""Pydantic models: everything exchanged between the scanner, the LLM and the report."""

from __future__ import annotations

from enum import StrEnum
from typing import Literal

from pydantic import BaseModel, Field


class Severity(StrEnum):
    low = "low"
    medium = "medium"
    high = "high"
    critical = "critical"

    @property
    def rank(self) -> int:
        return ["low", "medium", "high", "critical"].index(self.value)


Category = Literal[
    "dead_code",
    "swallowed_error",
    "duplication",
    "misplaced_logic",
    "complexity",
    "long_function",
    "stale_doc",
    "lint",
    "other",
]


class Finding(BaseModel):
    file: str = Field(description="Path relative to the analysed project root")
    line: int = Field(ge=0, description="Line concerned (0 for the whole file)")
    category: Category
    severity: Severity
    explanation: str = Field(description="What is wrong and why it matters")
    suggestion: str = Field(description="Concrete proposed fix")
    source: Literal["scanner", "llm"] = "llm"


class MoveSpec(BaseModel):
    """Deterministic move of a top-level symbol (performed by libcst, never by the LLM)."""

    source_file: str = Field(description="File that defines the symbol, relative to the root")
    symbol: str = Field(description="Name of the top-level function or class to move")
    dest_file: str = Field(description="Destination file, e.g. app/services/resolution.py")


class RefactorStep(BaseModel):
    id: int = Field(ge=1)
    title: str = Field(description="Short title, used as the commit message")
    kind: Literal["move", "edit"] = Field(
        description="'move': move symbols and rewrite imports (deterministic). "
        "'edit': content change generated by the LLM."
    )
    description: str = Field(description="What exactly the step changes")
    files: list[str] = Field(default_factory=list, description="Files touched by the step")
    moves: list[MoveSpec] = Field(default_factory=list, description="Only for kind='move'")
    rationale: str = Field(default="", description="Finding(s) the step resolves")


class RefactorPlan(BaseModel):
    target_architecture: str = Field(
        description="Target architecture, e.g. 'business logic in app/services/, thin views'"
    )
    steps: list[RefactorStep] = Field(default_factory=list)


class AnalysisResult(BaseModel):
    """Structured output of the analysis loop."""

    findings: list[Finding] = Field(default_factory=list)
    plan: RefactorPlan


class FileEdit(BaseModel):
    path: str = Field(description="Path relative to the project root")
    content: str = Field(description="COMPLETE new content of the file")


class StepEdits(BaseModel):
    """Structured output of the refactoring loop for an 'edit' step."""

    edits: list[FileEdit] = Field(default_factory=list)
    summary: str = Field(default="", description="One-sentence summary of the change")


class StepStatus(StrEnum):
    applied = "applied"
    failed = "failed"
    skipped = "skipped"
    simulated = "simulated"


class StepResult(BaseModel):
    step: RefactorStep
    status: StepStatus
    commit: str | None = None
    detail: str = ""
    diff: str = ""
    attempts: int = 0
